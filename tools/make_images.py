#!/usr/bin/env python3
"""Turn the two 400x300 PNGs into src/signs.h.

Packing matches the ATC1441 uploader with 400x300 BWR, Compression off,
Dithering off, Mirror Image off, Second Color on: the image is read row
by row, 8 pixels per byte (first pixel in the top bit). The black layer comes first (1 = light),
then the red layer (1 = red).
"""
import hashlib, pathlib, sys
from PIL import Image

W, H = 400, 300
ROOT = pathlib.Path(__file__).resolve().parent.parent

def pack(path):
    img = Image.open(path).convert("RGB")
    if img.size != (W, H):
        sys.exit(f"{path} must be {W}x{H}, got {img.size}")
    px = img.load()
    black, red = bytearray(), bytearray()
    cur_b = cur_r = 0
    bit = 7
    for y in range(H):
        for x in range(W):
            r, g, b = px[x, y]
            if 0.2126 * r + 0.7152 * g + 0.0722 * b > 128:
                cur_b |= 1 << bit
            if r > 170 and g < 170:
                cur_r |= 1 << bit
            bit -= 1
            if bit < 0:
                black.append(cur_b); red.append(cur_r)
                cur_b = cur_r = 0
                bit = 7
    return bytes(black + red)

def c_array(name, data):
    rows = [", ".join(f"0x{v:02x}" for v in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"static const uint8_t {name}[{len(data)}] = {{\n  " + ",\n  ".join(rows) + "\n};\n"

signs = {
    "SIGN_OPEN": pack(ROOT / "images/sign-open-400x300.png"),
    "SIGN_DND": pack(ROOT / "images/sign-dnd-400x300.png"),
}
out = "// Generated by tools/make_images.py. Do not edit by hand.\n#pragma once\n#include <stdint.h>\n\n"
out += "\n".join(c_array(k, v) for k, v in signs.items())
(ROOT / "src/signs.h").write_text(out)
for k, v in signs.items():
    print(k, len(v), hashlib.sha256(v.hex().encode()).hexdigest())
